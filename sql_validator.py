from __future__ import annotations
import re
import sqlparse

DANGEROUS_KEYWORDS = {
    "DROP", "DELETE", "UPDATE", "INSERT", "ALTER", "TRUNCATE",
    "CREATE", "REPLACE", "GRANT", "REVOKE", "EXEC", "EXECUTE",
    "CALL", "LOAD_FILE", "INTO OUTFILE", "INTO DUMPFILE",
}

class ValidationError(Exception):
    pass

def validate_sql(sql: str, known_tables: list[str]) -> str:
    if not sql or not sql.strip():
        raise ValidationError("Empty SQL generated by the model.")
    
    cleaned = sql.strip()
    cleaned = re.sub(r"^```(?:sql)?\s*", "", cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(r"\s*```$", "", cleaned).strip()
    cleaned = cleaned.strip("`")
    
    statements = [s for s in sqlparse.split(cleaned) if s.strip()]
    if len(statements) != 1:
        raise ValidationError(
            f"Expected exactly one SQL statement, got {len(statements)}. Stacked queries are blocked."
        )
    
    single = statements[0].strip().rstrip(";")
    upper = single.upper()
    
    if not (upper.startswith("SELECT") or upper.startswith("WITH")):
        raise ValidationError("Only SELECT statements are allowed.")
    
    for word in DANGEROUS_KEYWORDS:
        if re.search(rf"\b{re.escape(word)}\b", upper):
            raise ValidationError(f"Blocked keyword detected: {word}")
    
    # 1. Recognize Common Table Expressions (CTEs) so they aren't rejected as unknown tables
    cte_names = re.findall(r"(?:WITH|,)\s*`?([a-zA-Z_]\w*)`?\s+AS\s*\(", single, flags=re.IGNORECASE)
    known_set = {kt.lower() for kt in known_tables}
    known_set.update(c.lower() for c in cte_names)

    # 2. Matches table names in statements including backtick wrapping and aliases
    referenced_raw = re.findall(r"(?:FROM|JOIN)\s+(?:`?\w+`?\.)?`?(\w+)`?", single, flags=re.IGNORECASE)
    unknown = [t for t in referenced_raw if t.lower() not in known_set]
    
    if unknown:
        raise ValidationError(f"Query references unknown table(s): {unknown}")
    
    # 3. Auto-LIMIT Safeguard: Prevent unbounded queries from exhausting server memory
    if not re.search(r"\bLIMIT\s+\d+", single, flags=re.IGNORECASE):
        single = f"{single} LIMIT 500"

    return single

def format_sql(sql: str) -> str:
    return sqlparse.format(sql, reindent=True, keyword_case="upper")